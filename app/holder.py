"""Детерминированная генерация ФИО держателя по реквизиту.

Реальных персональных данных в эмуляторе нет. ФИО вычисляется из цифр реквизита,
поэтому один и тот же реквизит всегда даёт одно и то же ФИО (детерминированный
тестовый двойник).
"""
import hashlib

# Фамилии хранятся в мужской форме; для женского ФИО добавляется «а»
# (Иванов → Иванова) — для этих окончаний (-ов/-ев/-ин) правило работает.
_SURNAME_BASES = [
    "Иванов", "Петров", "Смирнов", "Кузнецов", "Попов", "Соколов",
    "Лебедев", "Козлов", "Новиков", "Морозов", "Волков", "Васильев",
    "Зайцев", "Павлов", "Семёнов", "Богданов",
]
_MALE_FIRST = [
    "Александр", "Дмитрий", "Максим", "Сергей", "Андрей", "Алексей",
    "Иван", "Михаил", "Никита", "Егор", "Артём", "Роман",
]
_MALE_PATR = [
    "Александрович", "Дмитриевич", "Сергеевич", "Андреевич",
    "Иванович", "Михайлович", "Николаевич", "Петрович",
]
_FEMALE_FIRST = [
    "Анна", "Мария", "Елена", "Ольга", "Наталья", "Екатерина",
    "Ирина", "Татьяна", "София", "Виктория", "Дарья", "Анастасия",
]
_FEMALE_PATR = [
    "Александровна", "Дмитриевна", "Сергеевна", "Андреевна",
    "Ивановна", "Михайловна", "Николаевна", "Петровна",
]


def holder_name(requisite: str) -> str:
    """Вернуть ФИО в порядке «Фамилия Имя Отчество»."""
    digits = "".join(ch for ch in requisite if ch.isdigit()) or requisite
    h = int(hashlib.sha256(digits.encode("utf-8")).hexdigest(), 16)

    female = (h & 1) == 1
    surname = _SURNAME_BASES[(h >> 1) % len(_SURNAME_BASES)]
    if female:
        surname += "а"
        first = _FEMALE_FIRST[(h >> 8) % len(_FEMALE_FIRST)]
        patronymic = _FEMALE_PATR[(h >> 16) % len(_FEMALE_PATR)]
    else:
        first = _MALE_FIRST[(h >> 8) % len(_MALE_FIRST)]
        patronymic = _MALE_PATR[(h >> 16) % len(_MALE_PATR)]

    return f"{surname} {first} {patronymic}"
